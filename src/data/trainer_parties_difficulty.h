// Gym leader, Elite Four and Champion teams for the Medium and Hard
// difficulties (see include/difficulty.h). This file is only included when
// DIFF_BOSS_TEAMS is set; otherwise the original teams in trainer_parties.h
// are used.
//
// Levels written here are the base levels: they are still scaled at battle
// time by DIFF_TRAINER_LEVEL_PERCENT, like every other trainer.
//
// Medium: same teams as the original, but with moves chosen for type coverage
//         and status, plus a few held items.
// Hard:   optimized teams with extra Pokemon, held items and weather setups
//         (Rain Dance, Sunny Day, Sandstorm, Hail).

#define BOSS_MON(species_, lvl_, item_, move1, move2, move3, move4) \
    {                                                               \
        .iv = DIFF_BOSS_IV,                                         \
        .lvl = (lvl_),                                              \
        .species = (species_),                                      \
        .heldItem = (item_),                                        \
        .moves = {(move1), (move2), (move3), (move4)},              \
    }

